// Take a char and: 
// Print ASCII value 
// Print next 2 characters


package datatype;

public class ASCII {
    public static void main(String[] args) {
        char a = 'D';
        System.out.println("Value of a ::" + a);
        System.out.println("ASCII Value ::"+ (int)a);
        System.out.println("Next ASCII Value  ::"+ (int)(a+1));
        System.out.println("Next+2 ASCII Value ::"+ (int)(a+2));
        
    }
    
}
